"""CLI for deterministic LSAF DAG and human projections.

Usage:
  python -m lsaf.compiler.run --manifest lsaf/handover/manifest.yaml \
      --graph lsaf/state/p0_work_graph.yaml --out lsaf/generated/p0

Use --check to compare generated bytes with existing files without rewriting them.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from lsaf.compiler.dag import compile_dag
from lsaf.compiler.project import project_all


def _yaml():
    try:
        import yaml
    except ImportError as exc:
        raise SystemExit("PyYAML is required (Hub pin: pyyaml>=6.0.3)") from exc
    return yaml


def load(path: Path):
    return _yaml().safe_load(path.read_text(encoding="utf-8"))


def build(manifest_path: Path, graph_path: Path) -> dict[str, str]:
    manifest = load(manifest_path)
    graph = load(graph_path)
    dag = compile_dag(graph.get("nodes") or [])
    return project_all(manifest, dag)


def write_or_check(outputs: dict[str, str], out: Path, check: bool) -> int:
    mismatches = []
    for name, content in sorted(outputs.items()):
        path = out / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                mismatches.append(name)
        else:
            out.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if mismatches:
        print("LSAF projection mismatch:", ", ".join(mismatches))
        return 1
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", type=Path, required=True)
    ap.add_argument("--graph", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    return write_or_check(build(args.manifest, args.graph), args.out, args.check)


if __name__ == "__main__":
    raise SystemExit(main())
