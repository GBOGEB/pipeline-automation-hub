def canon(value):
    return (json.dumps(value, sort_keys=True, indent=2,
                       ensure_ascii=True, allow_nan=False) + "\n").encode()


def hash_bytes(data):
    return hashlib.sha256(data).hexdigest()


def require(condition, code):
    if not condition:
        raise ValueError(code)


def exact_head(root, head):
    require(bool(SHA40.fullmatch(head or "")), "SOURCE_HEAD_SHA_INVALID")
    process = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                             capture_output=True, text=True, timeout=10, check=False)
    require(process.returncode == 0 and process.stdout.strip() == head,
            "SOURCE_CHECKOUT_HEAD_MISMATCH")
    return head


def load_inputs(root):
    raw = (root / INPUT).read_bytes()
    original = json.loads(raw)
    altered = copy.deepcopy(original)
    first = next((row for cohort in altered["cohorts"] for row in cohort["runs"]
                  if row.get("conclusion") == "success"), None)
    require(first is not None, "NO_COUNTERFACTUAL_SOURCE_EVENT")
    first["conclusion"] = "failure"
    invalid = copy.deepcopy(original)
    invalid["cohorts"][0]["returned_count"] += 1
    return {"baseline": original, "counterfactual": altered,
            "invalid": invalid}, hash_bytes(raw)


def tasks_for(n):
    require(type(n) is int and n in (8, 16, 32), "TASK_COUNT_OUT_OF_BOUNDS")
    return [{"id": f"T{i:03d}",
             "kind": ("invalid" if i % 8 == 0 else
                      "counterfactual" if i % 8 == 1 else "baseline")}
            for i in range(n)]


def plan(pulses, n):
    require(type(pulses) is int and 1 <= pulses <= MAX_PULSES,
            "PULSE_COUNT_OUT_OF_BOUNDS")
    rows = tasks_for(n)
    order = list(LANES)
    blocks = []
    for pulse in range(1, pulses + 1):
        # ABBA balances transient thermal/cache/order effects for cold16 vs cold32.
        lanes = order if pulse % 4 in (1, 0) else list(reversed(order))
        ranked = sorted(rows, key=lambda r: hash_bytes(
            f"{pulse}:{r['id']}".encode("ascii")))
        blocks.append({"pulse": pulse, "lanes": lanes,
                       "task_ids": [r["id"] for r in ranked]})
    return rows, blocks


def producer_module(root):
    spec = importlib.util.spec_from_file_location("method_atlas_existing_g9_producer",
                                                   root / G9)
    require(spec is not None and spec.loader is not None,
            "EXISTING_G9_PRODUCER_UNAVAILABLE")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def verify_output(out, head, kind):
    """Read actual generated bytes; never trust exit code alone."""
    require(out.is_dir(), "G9_REQUIRED_OUTPUT_DIRECTORY_MISSING")
    members = set(p.name for p in out.iterdir())
    require(members == MEMBERS | {"manifest.json"}, "G9_MEMBER_SET_MISMATCH")
    manifest = json.loads((out / "manifest.json").read_bytes())
    require(manifest.get("source_sha") == head and
            manifest.get("merge_authorized") is False and
            set(manifest.get("files", {})) == MEMBERS,
            "G9_MANIFEST_SOURCE_OR_MEMBER_MISMATCH")
    for name, expected in manifest["files"].items():
        require(hash_bytes((out / name).read_bytes()) == expected,
                "G9_PRODUCT_HASH_MISMATCH")
    metrics = json.loads((out / "metrics.json").read_bytes())
    observed = (metrics.get("total_native_runs"),
                metrics.get("native_terminal_success"),
                metrics.get("native_terminal_failure"),
                metrics.get("native_terminal_cancelled"))
    require(observed == EXPECTED[kind], "G9_SEMANTIC_OUTCOME_MISMATCH")
    return hash_bytes(canon(manifest["files"]))


def run_case(task, root, input_files, objects, out, head, mode, producer, tracker):
    started = time.perf_counter()
    tracker["lock"].acquire()
    tracker["active"] += 1
    tracker["peak"] = max(tracker["peak"], tracker["active"])
    tracker["lock"].release()
    try:
        kind = task["kind"]
        error_class = None
        if mode == "SUBPROCESS_CLI":
            command = [sys.executable, str(root / G9), "--input",
                       str(input_files[kind]), "--out", str(out),
                       "--source-sha", head]
            environment = dict(os.environ)
            environment["PYTHONDONTWRITEBYTECODE"] = "1"
            try:
                completed = subprocess.run(command, cwd=root,
                                           capture_output=True, timeout=30,
                                           check=False, env=environment)
                success = completed.returncode == 0
                error_class = ("EXPECTED_SOURCE_DENOMINATOR" if NEGATIVE.encode()
                               in completed.stderr else
                               "NO_EXPECTED_DENOMINATOR_REJECTION")
            except subprocess.TimeoutExpired:
                raise ValueError("G9_READONLY_TASK_TIMEOUT")
        else:
            require(mode == "IN_PROCESS_LIBRARY", "UNKNOWN_ALLOWED_SCOUT_BACKEND")
            try:
                producer.build(copy.deepcopy(objects[kind]), out, head)
                success = True
            except ValueError as exc:
                success = False
                error_class = ("EXPECTED_SOURCE_DENOMINATOR" if NEGATIVE in str(exc)
                               else "NO_EXPECTED_DENOMINATOR_REJECTION")
        if kind == "invalid":
            require(not success and error_class == "EXPECTED_SOURCE_DENOMINATOR",
                    "INVALID_INPUT_NOT_REJECTED_BY_RIGHT_ORACLE")
            require(not out.exists() or not any(out.iterdir()),
                    "INVALID_INPUT_PRODUCED_UNAUTHORIZED_OUTPUT")
            result = "EXPECTED_REJECTION"
        else:
            require(success, "VALID_PRODUCTION_PROCESS_FAILED")
            result = verify_output(out, head, kind)
        elapsed = time.perf_counter() - started
        return {"id": task["id"], "kind": kind, "elapsed_seconds": round(elapsed, 6),
                "outcome": ("REJECTED_EXPECTED" if kind == "invalid" else "VALID_VERIFIED"),
                "output_digest": result}
    finally:
        tracker["lock"].acquire()
        tracker["active"] -= 1
        tracker["lock"].release()


def percentile_nearest(values, probability):
    require(bool(values) and 0 <= probability <= 1, "PERCENTILE_POPULATION_INVALID")
    ordered = sorted(values)
    return ordered[max(0, math.ceil(len(ordered) * probability) - 1)]


def execute_lane(root, inputs, input_files, head, producer, lane, tasks,
                 pulse, workdir):
    workers, mode = LANES[lane]
    work = workdir / f"pulse{pulse}-{lane}"
    work.mkdir(parents=True)
    tracker = {"lock": threading.Lock(), "active": 0, "peak": 0}
    started = time.perf_counter()
    result = {}
    completion = []
    # ThreadPoolExecutor is only a bounded local read-only scout carrier.
    # Every cold task runs the approved G9 CLI; no external code or network.
    with ThreadPoolExecutor(max_workers=workers) as pool:
        pending = {pool.submit(run_case, task, root, input_files, inputs,
                               work / task["id"], head, mode, producer, tracker): task
                   for task in tasks}
        for future in as_completed(pending):
            row = future.result()  # actual exception is a fail-closed first-red
            result[row["id"]] = row
            completion.append(row["id"])
    elapsed = time.perf_counter() - started
    require(len(result) == len(tasks) and len(completion) == len(tasks)
            and len(set(completion)) == len(tasks), "TASK_FAN_IN_LOSS_OR_DUPLICATE")
    require(tracker["active"] == 0 and 1 <= tracker["peak"] <= workers,
            "LOCAL_SCOUT_COUNTER_INCONSISTENT")
    valid = sum(r["outcome"] == "VALID_VERIFIED" for r in result.values())
    rejected = sum(r["outcome"] == "REJECTED_EXPECTED" for r in result.values())
    require(valid + rejected == len(tasks), "SILENT_TASK_OUTCOME_MISSING")
    durations = [r["elapsed_seconds"] for r in result.values()]
    return {
        "pulse": pulse, "lane": lane, "requested_workers": workers,
        "observed_peak_local_tasks": tracker["peak"],
        "backend": mode, "wall_seconds": round(elapsed, 6),
        "accepted_outputs": valid, "negative_rejections": rejected,
        "task_p50_seconds": round(statistics.median(durations), 6),
        "task_p95_seconds": round(percentile_nearest(durations, .95), 6),
        "verified_outputs_per_second": round(valid / elapsed, 6),
        "task_completion_order_sha256": hash_bytes(canon(completion)),
        "task_receipts": [result[k] for k in sorted(result)],
        "native_qualified": False,
    }


def compare_lanes(rows):
    evidence = {}
    baseline = None
    for row in rows:
        by_task = {r["id"]: (r["kind"], r["outcome"], r["output_digest"])
                   for r in row["task_receipts"]}
        if baseline is None:
            baseline = by_task
        require(by_task == baseline, "CROSS_LANE_OUTCOME_PARITY_FAILURE")
        evidence[row["lane"]] = row
    require(set(evidence) == set(LANES), "MISSING_SCALE_LANE")
    expected_rejections = sum(r["kind"] == "invalid"
                              for r in evidence["cold1"]["task_receipts"])
    for lane, row in evidence.items():
        require(row["negative_rejections"] == expected_rejections,
                "NEGATIVE_CONTROL_COHORT_MISMATCH")
    return evidence


def summarize(blocks):
    modes = {}
    for lane in LANES:
        group = [row for block in blocks for row in block["cohorts"] if row["lane"] == lane]
        throughputs = [r["verified_outputs_per_second"] for r in group]
        walls = [r["wall_seconds"] for r in group]
        modes[lane] = {
            "workers": LANES[lane][0], "backend": LANES[lane][1],
            "pulses": len(group), "total_accepted_outputs": sum(r["accepted_outputs"] for r in group),
            "total_negative_rejections": sum(r["negative_rejections"] for r in group),
            "wall_seconds_total": round(sum(walls), 6),
            "median_wall_seconds": round(statistics.median(walls), 6),
            "median_outputs_per_second": round(statistics.median(throughputs), 6),
            "median_task_p95_seconds": round(statistics.median(
                r["task_p95_seconds"] for r in group), 6),
            "observed_peak_local_tasks": max(r["observed_peak_local_tasks"] for r in group),
        }
    pairs = []
    for block in blocks:
        cohort = {row["lane"]: row for row in block["cohorts"]}
        speed32 = cohort["cold16"]["wall_seconds"] / cohort["cold32"]["wall_seconds"]
        speedwarm = cohort["cold16"]["wall_seconds"] / cohort["warm16"]["wall_seconds"]
        pairs.append({
            "pulse": block["pulse"], "cold32_vs_cold16_speedup": round(speed32, 4),
            "warm16_vs_cold16_speedup": round(speedwarm, 4),
        })
    return {"by_mode": modes, "paired": pairs,
            "median_cold32_vs_cold16_speedup": round(statistics.median(
                x["cold32_vs_cold16_speedup"] for x in pairs), 4),
            "median_warm16_vs_cold16_speedup": round(statistics.median(
                x["warm16_vs_cold16_speedup"] for x in pairs), 4),
            "inference": "DESCRIPTIVE_SAME_RUNNER_REPEATS_NOT_INDEPENDENT_NATIVE_PULSES",
            "confidence_interval": None, "causal_fleet_scale_proven": False}


