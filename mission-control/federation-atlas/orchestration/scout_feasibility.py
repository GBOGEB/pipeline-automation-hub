def run(root, head, out, pulses=4, task_count=32):
    root = Path(root).resolve()
    out = Path(out).resolve()
    require(out != root and not out.is_relative_to(root),
            "OUTPUT_DIRECTORY_INSIDE_SOURCE_CHECKOUT")
    require(not out.exists() or (out.is_dir() and not any(out.iterdir())),
            "OUTPUT_NOT_EMPTY")
    exact_head(root, head)
    inputs, raw_sha = load_inputs(root)
    tasks, blocks = plan(pulses, task_count)
    workload = {
        "task_count": len(tasks), "pulses": pulses,
        "input_sha256": raw_sha,
        "input_variants_sha256": {k: hash_bytes(canon(v)) for k, v in inputs.items()},
        "task_plan": tasks,
    }
    workload["sha256"] = hash_bytes(canon(workload))
    g9 = producer_module(root)
    env = {
        "python_version": platform.python_version(),
        "platform": platform.system(),
        "machine": platform.machine(),
        "available_cpu_count_observed": (len(os.sched_getaffinity(0)) if
                                         hasattr(os, "sched_getaffinity") else os.cpu_count()),
        "runner_label": os.environ.get("RUNNER_OS", "UNKNOWN"),
        "native_run_id_claim": os.environ.get("GITHUB_RUN_ID"),
        "native_job_id": None,
        "native_job_step_authenticated": False,
    }
    with tempfile.TemporaryDirectory(prefix="method-atlas-g9-scale-") as td:
        temp = Path(td)
        input_files = {}
        for kind, payload in inputs.items():
            dest = temp / (kind + ".json")
            dest.write_bytes(canon(payload))
            input_files[kind] = dest
        data = []
        expected = {t["id"]: t["kind"] for t in tasks}
        for block in blocks:
            order = sorted(tasks, key=lambda t: block["task_ids"].index(t["id"]))
            cohorts = []
            for lane in block["lanes"]:
                result = execute_lane(root, inputs, input_files, head, g9, lane,
                                      order, block["pulse"], temp)
                require({r["id"]: r["kind"] for r in result["task_receipts"]} == expected,
                        "WORKLOAD_IDENTITY_DRIFT")
                cohorts.append(result)
            compare_lanes(cohorts)
            data.append({"pulse": block["pulse"], "order": block["lanes"], "cohorts": cohorts,
                         "all_production_outputs_sha_verified": True})
        summary = summarize(data)
    workload["total_task_executions"] = pulses * task_count * len(LANES)
    workload["negative_rejections_total"] = sum(r["negative_rejections"]
                                                 for b in data for r in b["cohorts"])
    report = {
        "schema": SCHEMA,
        "source": {"repository": "GBOGEB/pipeline-automation-hub",
                   "head": head, "producer_path": str(G9),
                   "producer_identity": "EXISTING_G9_PRODUCTION_PROCESSOR"},
        "workload": workload, "environment": env,
        "blocks": data, "summary": summary,
        "safety": {"actual_entrypoint_invocations": True,
                   "remote_github_dispatch_performed": False,
                   "mutating_broker_policy_changed": False,
                   "source_files_modified": False, "input_private_qps": False,
                   "scale_promotion": False, "merger_admission": "HOLD",
                   "native_four_pulse_scout_gate": "NOT_SATISFIED",
                   "engineering_credit_delta": 0,
                   "reproducible_hashes_not_deterministic_wall_clock": True},
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / "scale_feasibility.json").write_bytes(canon(report))
    (out / "index.html").write_text(render(report), encoding="utf-8", newline="\n")
    (out / "execution_dag.mmd").write_text(
        """flowchart LR
  S["Git source HEAD + fixture digest"] --> P["Bounded read-only task plan"]
  P --> C1["CLI: 1,4,16,32 local subprocesses"]
  P --> C2["Warm16 in-process G9 library"]
  C1 --> O["Verify 4 output members + semantic counts"]
  C2 --> O
  P --> N["Invalid census negative oracle"]
  N --> O
  O --> F["Fan-in by task identity + paired pulses"]
  F --> H["Descriptive scale feasibility, owner HOLD"]
""", encoding="utf-8", newline="\n")
    members = ["scale_feasibility.json", "index.html", "execution_dag.mmd"]
    manifest = {
        "schema": "method-atlas.g9-local-scale-manifest.v1",
        "source_head": head, "workload_sha256": workload["sha256"],
        "files": {p: hash_bytes((out / p).read_bytes()) for p in members},
        "native_jobs_authenticated": False,
        "scale_promotion": False, "merger_admission": "HOLD",
    }
    (out / "manifest.json").write_bytes(canon(manifest))
    print(json.dumps({
        "status": "PASS_LOCAL_READONLY_FEASIBILITY",
        "head": head, "tasks": workload["total_task_executions"],
        "negative_controls": workload["negative_rejections_total"],
        "median_32_vs_16": summary["median_cold32_vs_cold16_speedup"],
        "median_warm16_vs_cold16": summary["median_warm16_vs_cold16_speedup"],
        "native_scale_qualified": False,
    }, sort_keys=True))
    return report


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--head", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--pulses", type=int, default=4)
    ap.add_argument("--tasks", type=int, default=32)
    args = ap.parse_args(argv)
    run(args.root, args.head, args.out, args.pulses, args.tasks)
    return 0


