"""Source-bounded local HTML QA: 3 viewports, keyboard, expansion, duplication, no fake live."""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.parse import urlsplit
from playwright.sync_api import sync_playwright


def qa(path, output, head):
    html=Path(path).resolve(); out=Path(output);out.mkdir(parents=True,exist_ok=True)
    checks=[]
    with sync_playwright() as p:
        executable='/usr/bin/chromium' if Path('/usr/bin/chromium').is_file() else None
        browser=p.chromium.launch(executable_path=executable,headless=True,args=['--no-sandbox'])
        for name,w,h in [('desktop',1440,1000),('laptop',1280,800),('mobile',390,844)]:
            page=browser.new_page(viewport={'width':w,'height':h},device_scale_factor=1)
            errs=[];requests=[]
            page.on('pageerror',lambda x:errs.append(str(x)))
            page.on('console',lambda x:errs.append(x.text) if x.type=='error' else None)
            page.on('request',lambda x:requests.append(x.url) if x.url.startswith('http') and not x.url.startswith('http://superstitch.local/') else None)
            # In managed/sandbox browsers, file:// and outbound navigations
            # are administratively blocked. Inject local generated bytes only.
            markup=html.read_text(encoding='utf-8')
            markup=(markup.replace('<link href="style.css" rel="stylesheet">','')
                .replace('<link href="stitch_interaction.css" rel="stylesheet">','')
                .replace('<script src="app.js" defer></script>','')
                .replace('<script src="stitch_interaction.js" defer></script>',''))
            page.set_content(markup,wait_until='load')
            page.add_style_tag(content=(html.parent/'style.css').read_text(encoding='utf-8'))
            page.add_style_tag(content=(html.parent/'stitch_interaction.css').read_text(encoding='utf-8'))
            page.add_script_tag(content=(html.parent/'app.js').read_text(encoding='utf-8'))
            page.add_script_tag(content=(html.parent/'stitch_interaction.js').read_text(encoding='utf-8'))
            page.wait_for_selector('#group-rail button.group-chip')
            node_count=page.locator('#graph-viewport svg .graph-node').count()
            assert node_count>=27,node_count
            assert page.locator('#graph-viewport svg .graph-node.alias').count()>=3
            assert page.locator('#graph-viewport svg .edge.touch').count()>=3
            assert page.locator('#sipoc-table tbody tr').count()==5
            assert page.locator('#activity-table tbody tr').count()==8
            assert '6/42' not in page.title(), 'Avoid title claim'
            assert '172/172' in page.locator('#kpis').inner_text()
            assert 'HOLD' in page.locator('.readiness').inner_text()
            # Interaction click -> canonical identity, depth and related links
            page.locator('#graph-viewport svg [data-node="keb-graph"]').click()
            assert 'KEB.GRAPH' in page.locator('#detail-inner').inner_text()
            assert 'Replay checks' in page.locator('#detail-inner').inner_text()
            assert page.locator('#detail-inner button').count()>=1
            page.locator('#graph-viewport svg [data-node="keb-duplicate"]').click()
            assert 'KEB.GRAPH' in page.locator('#detail-inner').inner_text()
            page.locator('#depth').select_option('2')
            assert page.locator('#graph-viewport svg [data-node="keb-duplicate"]').evaluate('(x)=>x.classList.contains("hidden")')
            page.locator('#show-all').click()
            assert not page.locator('#graph-viewport svg [data-node="keb-duplicate"]').evaluate('(x)=>x.classList.contains("hidden")')
            page.locator('#lens').select_option('flight')
            assert not page.locator('#graph-viewport svg [data-node="f0"]').evaluate('(x)=>x.classList.contains("hidden")')
            assert page.locator('#graph-viewport svg [data-node="keb-graph"]').evaluate('(x)=>x.classList.contains("hidden")')
            page.locator('#show-all').click()
            page.locator('#touch-toggle').click()
            assert page.locator('#graph-viewport svg .edge.touch:not(.hidden)').count()==0
            page.locator('#touch-toggle').click()
            assert page.locator('#graph-viewport svg .edge.touch:not(.hidden)').count()>=3
            page.locator('#expand-all').click()
            assert page.locator('#detail-inner details').count()>=22
            # W35 clickable source-only bounded groups, Mermaid and alternate DAG views
            assert page.locator('#group-rail button.group-chip').count()==10
            page.locator('#group-rail button[data-group="federation-touch"]').click()
            assert '0/1' in page.locator('#group-inspector').inner_text()
            assert '1 outstanding' in page.locator('#group-inspector').inner_text()
            assert page.locator('#graph-viewport [data-group-bound="federation-touch"]').count()>=2
            assert page.locator('#graph-viewport .graph-node.group-member').count()==5
            assert 'OWNER_DEFER' in page.locator('#group-inspector').inner_text()
            page.locator('#view-mode').select_option('sipoc')
            assert page.locator('#sipoc-lane-view .sipoc-group').count()==5
            page.locator('#sipoc-lane-view [data-group="math-methods"]').click()
            assert '172/172' in page.locator('#group-inspector').inner_text()
            assert '84/84' in page.locator('#group-inspector').inner_text()
            assert page.locator('#group-child-view .graph-node').count()==5
            page.locator('#view-mode').select_option('trigger')
            assert page.locator('#trigger-dag-view .graph-node').count()>=9
            assert page.locator('#trigger-edge-list button').count()>=4
            page.locator('#view-mode').select_option('spline')
            assert 'UNKNOWN' in page.locator('#spline-large-view').inner_text()
            page.locator('#view-mode').select_option('mermaid')
            assert 'flowchart LR' in page.locator('#mermaid-code').inner_text()
            assert 'n_math_provider' in page.locator('#mermaid-code').inner_text()
            page.locator('#group-rail button[data-group="alias-mycelium"]').click()
            assert 'TOPOLOGY_ONLY' in page.locator('#group-inspector').inner_text()
            assert 'n_dow_duplicate' in page.locator('#mermaid-code').inner_text()
            page.locator('#view-mode').select_option('group')
            page.locator('#group-child-view [data-node="dow-duplicate"]').click()
            assert 'DOW.RECEIPT' in page.locator('#detail-inner').inner_text()
            # A user rectangle creates a LOCAL_UI_ONLY selection, never source-native credit.
            page.locator('#lasso-enable').click()
            page.evaluate("""() => {
              const svg=document.querySelector('#graph-viewport svg');
              function send(type,x,y){const p=svg.createSVGPoint();p.x=x;p.y=y;
                const q=p.matrixTransform(svg.getScreenCTM());
                svg.dispatchEvent(new PointerEvent(type,{clientX:q.x,clientY:q.y,
                  button:0,pointerId:99,pointerType:'mouse',bubbles:true}));}
              send('pointerdown',185,115);send('pointermove',600,206);send('pointerup',600,206);
            }""")
            assert 'Local lasso' in page.locator('#group-inspector').inner_text()
            assert 'User-selected visual grouping only' in page.locator('#group-inspector').inner_text()
            page.locator('#lasso-clear').click()
            assert page.locator('#graph-viewport [data-group-bound]').count()==0
            page.locator('#lasso-enable').click()
            dims=page.evaluate('''() => ({viewport:innerWidth,body:document.documentElement.scrollWidth,
               broken:[...document.images].filter(i=>!i.complete||i.naturalWidth==0).length,
               graph_width:document.querySelector('.graph-viewport').scrollWidth,
               graph_container:document.querySelector('.graph-viewport').clientWidth})''')
            assert dims['body']<=w+1,dims
            assert dims['broken']==0,dims
            assert len(requests)==0,requests
            assert not errs,errs
            page.locator('#show-all').click()
            screenshot=out/(name+'.png');page.screenshot(path=str(screenshot),full_page=True)
            checks.append({'viewport':name,'width':w,'height':h,'node_count':node_count,
               'document_horizontal_overflow_px':max(0,dims['body']-w),
               'graph_internal_scroll':dims['graph_width']>dims['graph_container'],
               'page_errors':len(errs),'network_requests':len(requests),
               'broken_images':dims['broken'],'interactions':'PASS','w35_lasso_sipoc_mermaid_trigger_spline':'PASS','screenshot_sha256':hashlib.sha256(screenshot.read_bytes()).hexdigest()})
            page.close()
        browser.close()
    report={'schema':'missioncontrol.superstitch.browser_qa.v1','presentation_head':head,
       'evidence_level':'LOCAL_REPRODUCIBILITY','admission':'HOLD','checks':checks}
    (out/'browser_qa_receipt.json').write_text(json.dumps(report,indent=2)+'\n')
    return report

if __name__=='__main__':
    pa=argparse.ArgumentParser();pa.add_argument('--html',required=True);pa.add_argument('--out',required=True);pa.add_argument('--head',required=True);args=pa.parse_args()
    print(json.dumps(qa(args.html,args.out,args.head),indent=2))
